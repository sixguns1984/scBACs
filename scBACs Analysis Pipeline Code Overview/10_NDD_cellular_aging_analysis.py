# 7. OPTIONAL SST MOLECULAR SIGNATURE
# =============================================================================
# The working script contained a large collection of exploratory gene blocks. The
# final analysis needs only the intersection of AD DE with donor-level SST age
# association. This section is optional because raw expression resource paths vary.

def sst_gene_analysis(adata, metadata, subtype_col, label="Inh SST"):
    ids = adata.obs_names.intersection(metadata.index)
    a = adata[ids].copy()
    m = metadata.loc[ids].copy()
    for col in m.columns:
        a.obs[col] = m[col].values
    a = a[(a.obs[subtype_col].astype(str) == label) & a.obs["status"].isin(["CT", "AD"])].copy()
    if a.n_obs == 0:
        return pd.DataFrame()
    a = normalize_log1p(a)
    sc.tl.rank_genes_groups(a, "status", groups=["AD"], reference="CT", method="wilcoxon", pts=True)
    deg = sc.get.rank_genes_groups_df(a, group="AD").rename(columns={"names": "gene", "logfoldchanges": "AD_log2FC", "pvals": "AD_P", "pvals_adj": "AD_FDR"})

    # donor pseudobulk expression and donor-median SST cellular age
    donor_key = "donor_uid" if "donor_uid" in a.obs.columns else "donor_id"
    donor_age = a.obs.groupby(donor_key, observed=True)["scBAC_adult"].median()
    rows = []
    for gene in a.var_names:
        values = []
        ages = []
        for donor, idx in a.obs.groupby(donor_key, observed=True).indices.items():
            block = a[idx, gene].X
            x = float(np.asarray(block.mean()).reshape(-1)[0])
            values.append(x); ages.append(donor_age.loc[donor])
        if len(values) >= 5 and np.std(values) > 0:
            rho, p = spearmanr(values, ages)
            rows.append({"gene": str(gene), "age_spearman_rho": rho, "age_P": p})
    corr = pd.DataFrame(rows)
    if not corr.empty:
        corr["age_FDR"] = bh_fdr(corr["age_P"])
    out = deg.merge(corr, on="gene", how="inner")
    out["aging_consistent"] = ((out["AD_log2FC"] > 0) & (out["age_spearman_rho"] > 0)) | ((out["AD_log2FC"] < 0) & (out["age_spearman_rho"] < 0))
    return out

if RUN_SST_GENE_ANALYSIS:
    dis_gene = pd.DataFrame()
    rep_gene = pd.DataFrame()
    if ROSMAP_EXPRESSION.exists() and not sub_dis.empty:
        a = sc.read_h5ad(ROSMAP_EXPRESSION)
        dis_gene = sst_gene_analysis(a, sub_dis, SUBTYPE_COL)
        dis_gene.to_csv(RESULT_DIR / "SST_AD_aging_genes_discovery.csv", index=False)

    # Build the combined SEAAD + GSE263468 replication expression resource.
    rep_adatas = []
    rep_meta_parts = []
    for expr_path, meta_path in [(SEAAD_EXPRESSION, SEAAD_INH_METADATA), (GSE263468_EXPRESSION, GSE263468_INH_METADATA)]:
        if expr_path.exists() and meta_path.exists():
            m = pd.read_csv(meta_path, index_col=0)
            a = sc.read_h5ad(expr_path)
            ids = a.obs_names.intersection(m.index.astype(str))
            if len(ids):
                rep_adatas.append(a[ids].copy())
                rep_meta_parts.append(m.loc[ids])
    if rep_adatas:
        rep_expr = sc.concat(rep_adatas, axis=0, join="inner", merge="same", index_unique=None)
        rep_meta = pd.concat(rep_meta_parts, axis=0)
        rep_gene = sst_gene_analysis(rep_expr, rep_meta, SUBTYPE_COL)
        rep_gene.to_csv(RESULT_DIR / "SST_AD_aging_genes_replication.csv", index=False)

    if not dis_gene.empty and not rep_gene.empty:
        m = dis_gene.merge(rep_gene, on="gene", suffixes=("_dis", "_rep"))
        m["DE_concordant"] = np.sign(m["AD_log2FC_dis"]) == np.sign(m["AD_log2FC_rep"])
        m["Age_concordant"] = np.sign(m["age_spearman_rho_dis"]) == np.sign(m["age_spearman_rho_rep"])
        m["reproducible"] = (
            (m["AD_FDR_dis"] < 0.05) & (m["AD_P_rep"] < 0.05) &
            (m["age_FDR_dis"] < 0.05) & (m["age_P_rep"] < 0.05) &
            m["DE_concordant"] & m["Age_concordant"]
        )
        m["aging_consistent"] = (
            ((m["AD_log2FC_dis"] > 0) & (m["age_spearman_rho_dis"] > 0)) |
            ((m["AD_log2FC_dis"] < 0) & (m["age_spearman_rho_dis"] < 0))
        )
        final = m[m["reproducible"] & m["aging_consistent"]].copy()
        final.to_csv(RESULT_DIR / "SST_AD_aging_genes_reproducible.csv", index=False)
        go_dir = RESULT_DIR / "GO_input_gene_lists"
        go_dir.mkdir(exist_ok=True)
        up = final[(final["AD_log2FC_dis"] > 0) & (final["age_spearman_rho_dis"] > 0)]
        down = final[(final["AD_log2FC_dis"] < 0) & (final["age_spearman_rho_dis"] < 0)]
        pd.Series(sorted(up["gene"].astype(str).unique()), name="gene").to_csv(go_dir / "Inh_SST_AD_up_age_positive.csv", index=False)
        pd.Series(sorted(down["gene"].astype(str).unique()), name="gene").to_csv(go_dir / "Inh_SST_AD_down_age_negative.csv", index=False)

print("NDD cellular-age analysis complete.")
