# 5. AD PATHOLOGY / COGNITION
# =============================================================================
def attach_donor_phenotypes(donor_df, cell_df, columns):
    if donor_df.empty:
        return donor_df
    first = cell_df.drop_duplicates("donor_uid").set_index("donor_uid")
    keep = [c for c in columns if c in first.columns]
    out = donor_df.copy()
    for col in keep:
        out[col] = out["donor_uid"].map(first[col])
    return out

# Discovery: Braak, CERAD and reverse-coded MMSE quartile (higher = worse cognition).
dis_path = attach_donor_phenotypes(dis_donor, dis_cells, ["Braak_stage", "ceradsc", "MMSE"])
dis_path = dis_path[dis_path["status"] == "AD"].copy()
if "MMSE" in dis_path.columns:
    mmse_numeric = pd.to_numeric(dis_path["MMSE"], errors="coerce")
    valid = mmse_numeric.notna()
    if valid.sum() >= 4:
        try:
            q = pd.qcut(mmse_numeric[valid], q=4, labels=[4, 3, 2, 1], duplicates="drop")
            dis_path.loc[valid, "MMSE_impairment_quartile"] = pd.to_numeric(q, errors="coerce")
        except ValueError:
            pass


            
dis_pheno = [c for c in ["Braak_stage", "ceradsc", "MMSE_impairment_quartile"] if c in dis_path.columns]
if dis_pheno:
    run_pathology_associations(dis_path, dis_pheno).to_csv(
        RESULT_DIR / "AD_discovery_pathology_cognition_associations.csv", index=False
    )


# Replication: harmonize Braak, CERAD and cognitive status.
if not rep_donor.empty:
    rep_path = attach_donor_phenotypes(rep_donor, rep_cells, ["Braak_stage", "CERAD score", "Cognitive Status"])
    rep_path = rep_path[rep_path["status"] == "AD"].copy()
    if "Braak_stage" in rep_path.columns:
        braak_map = {"Braak 0": 0, "Braak I": 1, "Braak II": 2, "Braak III": 3, "Braak IV": 4, "Braak V": 5, "Braak VI": 6}
        rep_path["Braak_numeric"] = rep_path["Braak_stage"].replace(braak_map)
    if "CERAD score" in rep_path.columns:
        rep_path["CERAD_numeric"] = rep_path["CERAD score"].map({"Frequent": 1.0, "Moderate": 2.0, "Sparse": 3.0, "Absent": 4.0})
    if "Cognitive Status" in rep_path.columns:
        rep_path["Cognitive_impairment"] = rep_path["Cognitive Status"].map({"Dementia": 1.0, "No dementia": 0.0})
    rep_pheno = [c for c in ["Braak_numeric", "CERAD_numeric", "Cognitive_impairment"] if c in rep_path.columns]
    if rep_pheno:
        run_pathology_associations(rep_path, rep_pheno).to_csv(
            RESULT_DIR / "AD_replication_pathology_cognition_associations.csv", index=False
        )

