def load_subtype_metadata(paths, resource):
    parts = []
    for path in paths:
        if Path(path).exists():
            x = pd.read_csv(path, index_col=0)
            x["resource"] = resource
            parts.append(x)
    if not parts:
        return pd.DataFrame()
    d = pd.concat(parts, axis=0)
    d = add_scbac_adult(d)
    d = make_donor_uid(d)
    # Backward compatibility with working metadata.
    if SUBTYPE_COL not in d.columns:
        for candidate in ["sub_celltype2", "sub_celltype_celltypist", "sub_celltype_celltypist_coarse"]:
            if candidate in d.columns:
                d[SUBTYPE_COL] = d[candidate]
                break
    return d

sub_dis = load_subtype_metadata([ROSMAP_INH_METADATA], "Discovery")
sub_rep = load_subtype_metadata([SEAAD_INH_METADATA, GSE263468_INH_METADATA], "Replication")
sub_rep = sub_rep[sub_rep['sub_tissue']=='Prefrontal cortex'].copy()
for name, cells in [("discovery", sub_dis), ("replication", sub_rep)]:
    if cells.empty or SUBTYPE_COL not in cells.columns:
        continue
    d = cells[cells["status"].isin(["CT", "AD"])].copy()
    # Treat subtype as the analysis cell-type variable and summarize by donor.
    tmp = d.rename(columns={SUBTYPE_COL: "analysis_subtype"})
    donor = donor_median_summary(
        tmp, ["scBAC_adult"], celltype_col="analysis_subtype",
        metadata_cols=["status", "Sex", "Age_at_death", "PMI", "dataset", "sub_tissue"]
    )
    effect = run_donor_ad_age_ols(donor, celltype_col="analysis_subtype")
    effect.rename(columns={"CellType": "Inh_Subtype"}).to_csv(
        RESULT_DIR / f"AD_{name}_Inh_subtype_cellular_age_effect.csv", index=False
    )

