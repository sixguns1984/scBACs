# =============================================================================
def prepare_ad_resource(df, resource_name):
    d = df.copy()
    d = d[d["celltype"].isin(MAIN_CELLTYPES)]
    d = d[d["status"].isin(["CT", "AD"])]
    d = d[d["sub_tissue"].astype(str) == "Prefrontal cortex"]
    d = add_scbac_adult(d)
    d = make_donor_uid(d)
    d["resource"] = resource_name
    return d

