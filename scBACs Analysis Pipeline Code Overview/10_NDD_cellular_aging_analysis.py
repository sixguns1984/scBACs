"""
Effects of neurodegenerative diseases on scBAC-predicted cellular age.

Analyses retained from the final Methods:
- study-matched cell-level NDD effects across tissue x cell type (OLS)
- donor-median AD effect in ROSMAP PFC and SEAAD+GSE263468 PFC replication
- AD odds per 1-SD donor-median cellular-age increase
- associations with Braak/CERAD/cognition among AD donors
- AD effects and clinicopathological associations across 13 Inh subtypes
- SST molecular signature: AD differential expression intersected with genes associated
  with donor-median SST cellular age

Historical mixed-model and sensitivity-analysis blocks are intentionally omitted.
"""

