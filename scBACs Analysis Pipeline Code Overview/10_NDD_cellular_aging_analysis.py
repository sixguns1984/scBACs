for disease in NDD_LABELS:
    disease_studies = meta.loc[meta["status"].astype(str) == disease, "dataset"].dropna().unique()
    if len(disease_studies) == 0:
        continue
    d = meta[meta["dataset"].isin(disease_studies)].copy()
    # Prevent cross-contamination between the two disease labels in shared resources.
    if disease == "FTLD":
        d = d[d["status"] != "ALS"]
    if disease == "ALS":
        d = d[d["status"] != "FTLD"]
    d = d[d["status"].isin(["CT", disease])].copy()
    res = run_ndd_cellular_age_ols(d, disease_label=disease, outcome_col="scBAC_adult")
    if not res.empty:
        ndd_results.append(res)
        res.to_csv(RESULT_DIR / f"{disease}_cellular_age_effects.csv", index=False)

if ndd_results:
    pd.concat(ndd_results, ignore_index=True).to_csv(
        RESULT_DIR / "all_NDD_cellular_age_effects.csv", index=False
    )

