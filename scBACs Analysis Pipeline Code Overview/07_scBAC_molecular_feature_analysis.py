"""
Molecular feature analysis of the scBAC models.

This script reproduces two complementary analyses:

A. Genes associated with scBAC-predicted cellular age
   - analyzed separately for development and adult clocks;
   - training resource: donor-held-out OOF scBAC predictions;
   - independent multi-study validation: precomputed predictions generated by
     05_predict_scBAC_ensemble_fixed_pretrained.py;
   - Spearman correlation between log-normalized expression and predicted age;
   - training FDR < 0.05, validation P < 0.05, concordant direction;
   - top 100 genes by |Spearman r| per cell type for shared/unique analysis.

B. Model coefficient comparison
   - extract five-fold Elastic Net coefficients;
   - compare adult scBAC coefficients with the published Muralidharan human clock;
   - optionally compare glial scBAC coefficients with Buckley mouse clocks;
   - shared features require non-zero coefficients in both clocks with the same sign;
   - scBAC-specific features have non-zero scBAC coefficients but zero/absent
     coefficients in the comparison clock;
   - opposing signs are retained as a separate category, not as shared features.

GO Biological Process enrichment is performed in the companion R script:
07b_GO_enrichment.R
"""

