# ============================================================================
# 9. READ A PUBLISHED CLOCK COEFFICIENT TABLE
# ============================================================================


def read_published_clock_coefficients(
    clock_file,
    feature_col="clock feature (intercept or gene)",
    intercept_label="intercept"
):
    """Return one mean gene coefficient per feature from a published clock CSV."""

    clock_df = pd.read_csv(
        clock_file
    )

    # Support a few common public-table gene column names
    if feature_col not in clock_df.columns:
        gene_candidates = [
            col
            for col in clock_df.columns
            if str(col).lower() in [
                "gene",
                "genename",
                "feature",
                "clock_feature"
            ]
        ]

        if len(gene_candidates) == 0:
            raise KeyError(
                "No feature/gene column found in {}".format(
                    clock_file
                )
            )

        feature_col = gene_candidates[0]

    coefficient_cols = [
        col
        for col in clock_df.columns
        if "Fold" in str(col)
    ]

    if len(coefficient_cols) == 0:
        coefficient_cols = [
            col
            for col in clock_df.columns
            if str(col).lower() in [
                "coefficient",
                "coef",
                "weight"
            ]
        ]

    if len(coefficient_cols) == 0:
        raise KeyError(
            "No coefficient columns found in {}".format(
                clock_file
            )
        )

    gene_df = clock_df[
        clock_df[feature_col].astype(str)
        != intercept_label
    ].copy()

    for col in coefficient_cols:
        gene_df[col] = pd.to_numeric(
            gene_df[col],
            errors="coerce"
        ).fillna(0)

    result = pd.DataFrame(
        {
            "gene": gene_df[
                feature_col
            ].astype(str).values,
            "comparison_weight": gene_df[
                coefficient_cols
            ].mean(
                axis=1
            ).values
        }
    )

    return result


# ============================================================================
# 10. COMPARE SCBAC ELASTIC NET WITH PUBLISHED CLOCKS
# ============================================================================


def compare_clock_features(
    scbac_df,
    comparison_df,
    comparison_name,
    coefficient_definition="strict_consensus"
):
    """Classify shared, scBAC-specific, comparison-specific, and opposite-sign genes."""

    if coefficient_definition == "strict_consensus":
        scbac_use = scbac_df[
            [
                "gene",
                "strict_consensus_mean_weight"
            ]
        ].rename(
            columns={
                "strict_consensus_mean_weight": "scBAC_weight"
            }
        )
    elif coefficient_definition == "any_fold":
        scbac_use = scbac_df[
            [
                "gene",
                "mean_weight",
                "any_fold_nonzero"
            ]
        ].copy()

        scbac_use["scBAC_weight"] = np.where(
            scbac_use["any_fold_nonzero"],
            scbac_use["mean_weight"],
            0.0
        )

        scbac_use = scbac_use[
            [
                "gene",
                "scBAC_weight"
            ]
        ]
    else:
        raise ValueError(
            "coefficient_definition must be 'strict_consensus' or 'any_fold'"
        )

    merged = scbac_use.merge(
        comparison_df,
        on="gene",
        how="outer"
    )

    merged["scBAC_weight"] = merged[
        "scBAC_weight"
    ].fillna(0.0)

    merged["comparison_weight"] = merged[
        "comparison_weight"
    ].fillna(0.0)

    scbac_nonzero = merged[
        "scBAC_weight"
    ].ne(0)

    comparison_nonzero = merged[
        "comparison_weight"
    ].ne(0)

    same_sign = (
        np.sign(
            merged["scBAC_weight"]
        )
        == np.sign(
            merged["comparison_weight"]
        )
    )

    merged["feature_class"] = "Neither"

    merged.loc[
        scbac_nonzero
        & comparison_nonzero
        & same_sign,
        "feature_class"
    ] = "Shared_same_sign"

    merged.loc[
        scbac_nonzero
        & ~comparison_nonzero,
        "feature_class"
    ] = "scBAC_specific"

    merged.loc[
        ~scbac_nonzero
        & comparison_nonzero,
        "feature_class"
    ] = "Comparison_specific"

    merged.loc[
        scbac_nonzero
        & comparison_nonzero
        & ~same_sign,
        "feature_class"
    ] = "Opposite_sign"

    merged["comparison_clock"] = comparison_name

    return merged


