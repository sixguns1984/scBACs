def normalize_adata(adata):
    adata = adata.copy()
    adata.X = adata.X.astype("float32")
    sc.pp.normalize_per_cell(
        adata
    )
    sc.pp.log1p(
        adata
    )
    return adata


def calculate_gene_correlations(
    adata,
    predicted_age,
    chunk_size=200
):
    """
    Calculate cell-level Spearman correlation for every gene in one cell type.

    Gene expression is processed in chunks to avoid converting the complete
    single-cell matrix to a dense array at once.
    """

    predicted_age = np.asarray(
        predicted_age,
        dtype=float
    )

    if len(predicted_age) != adata.n_obs:
        raise ValueError(
            "predicted_age length does not match AnnData cells"
        )

    result_rows = []

    for start in range(
        0,
        adata.n_vars,
        chunk_size
    ):
        stop = min(
            start + chunk_size,
            adata.n_vars
        )

        gene_names = adata.var_names[
            start:stop
        ].astype(str)

        X_chunk = adata[
            :,
            start:stop
        ].X

        if sparse.issparse(
            X_chunk
        ):
            X_chunk = X_chunk.toarray()
        else:
            X_chunk = np.asarray(
                X_chunk
            )

        for gene_index, gene in enumerate(
            gene_names
        ):
            expression = X_chunk[
                :,
                gene_index
            ]

            valid = (
                np.isfinite(
                    expression
                )
                & np.isfinite(
                    predicted_age
                )
            )

            if valid.sum() < 3:
                rho = np.nan
                p_value = np.nan
            elif np.std(
                expression[valid]
            ) == 0:
                rho = np.nan
                p_value = np.nan
            else:
                rho, p_value = spearmanr(
                    expression[valid],
                    predicted_age[valid]
                )

            result_rows.append(
                {
                    "gene": gene,
                    "spearman_rho": rho,
                    "p_value": p_value,
                    "n_cells": int(valid.sum())
                }
            )

        print(
            "  Genes {:,}-{:,.0f} / {:,}".format(
                start + 1,
                stop,
                adata.n_vars
            )
        )

    result_df = pd.DataFrame(
        result_rows
    )

    return result_df


def add_fdr(result_df):
    result_df = result_df.copy()
    result_df["fdr"] = np.nan

    valid = result_df["p_value"].notna()

    if valid.sum() > 0:
        result_df.loc[
            valid,
            "fdr"
        ] = multipletests(
            result_df.loc[
                valid,
                "p_value"
            ],
            method="fdr_bh"
        )[1]

    return result_df


def align_adata_and_predictions(
    adata,
    prediction_df,
    prediction_col
):
    """Align AnnData cells to a prediction table by cell ID."""

    prediction_df = prediction_df.copy()

    if "cell_id" in prediction_df.columns:
        prediction_df.index = prediction_df[
            "cell_id"
        ].astype(str)
    else:
        prediction_df.index = prediction_df.index.astype(str)

    adata_index = pd.Index(
        adata.obs_names.astype(str)
    )

    common_cells = adata_index.intersection(
        prediction_df.index
    )

    if len(common_cells) == 0:
        raise ValueError(
            "No common cell IDs were found between expression and predictions"
        )

    adata_use = adata[
        common_cells,
        :
    ].copy()

    prediction_use = prediction_df.loc[
        common_cells,
        :
    ].copy()

    return (
        adata_use,
        prediction_use,
        pd.to_numeric(
            prediction_use[prediction_col],
            errors="coerce"
        ).values
    )


